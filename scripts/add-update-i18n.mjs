for (const locale of locales) {
  const file = `webapp/src/lib/i18n/locales/${locale}.ts`;
  let content = readFileSync(file, 'utf8');
  const insertAt = content.lastIndexOf('\n});');
  if (insertAt < 0) {
    console.error(`Cannot find closing brace in ${locale}.ts`);
    process.exit(1);
  }
  const beforeClose = content.slice(0, insertAt).replace(/\s+$/, '');
  if (!/[,\{\(\[]$/.test(beforeClose)) {
    const tailStart = beforeClose.lastIndexOf('\n');
    const lastLine = beforeClose.slice(tailStart + 1);
    content = content.slice(0, insertAt - lastLine.length) + lastLine + ',' + content.slice(insertAt);
  }
  const entries = Object.entries(values[locale]);
  const lines = entries.map(([key, value]) => `  "${key}": ${JSON.stringify(value)},`);
  content = content.slice(0, insertAt + 1) + '\n' + lines.join('\n') + '\n' + content.slice(insertAt + 1);
  writeFileSync(file, content);
  console.log(`patched ${locale}: ${entries.length} keys`);
}
